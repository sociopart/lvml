static const char* kGeneratedRules = R"(/* generated by html2lvml: HTML normal flow expressed as LVGL flex */
.lv-col  { layout: flex; flex-flow: column; }
.lv-row  { layout: flex; flex-flow: row-wrap; align-items: center; }
.lv-fill { width: 100%; }
.lv-grow { flex-grow: 1; }
.lv-bg   { position: absolute; x: 0; y: 0; width: 100%; height: 100%; }
)";

bool CHtmlConverter::ReadFile(const std::string& path, std::string& out)
{
    std::ifstream f(std::filesystem::u8path(path), std::ios::binary);
    if (!f) return false;
    std::stringstream ss;
    ss << f.rdbuf();
    out = ss.str();
    return true;
}

void CHtmlConverter::CollectStyles(CLvmlNode& root, const std::string& htmlDir, CLvssStyleSheet& css, CConversionReport& report)
{
    std::vector<CLvmlNode*> nodes;
    std::vector<CLvmlNode*> styles, links;
    root.FindAll("style", styles);
    root.FindAll("link", links);
    // Keep document order: walk all elements once.
    std::vector<CLvmlNode*> ordered;
    std::vector<CLvmlNode*> stack{ &root };
    while (!stack.empty()) {
        CLvmlNode* n = stack.back();
        stack.pop_back();
        if (n->IsTag("style") || n->IsTag("link")) ordered.push_back(n);
        for (auto it = n->GetChildren().rbegin(); it != n->GetChildren().rend(); ++it)
            if ((*it)->IsElement()) stack.push_back(it->get());
    }

    auto parse = [&](const std::string& text, const std::string& name) {
        CLvssStyleSheet sheet;
        sheet.SetPath(name);
        std::vector<std::string> warnings;
        CLvssParser::Parse(text, sheet, &warnings);
        for (const std::string& w : warnings) report.Drop(name, w);
        css.Append(sheet);
    };

    for (CLvmlNode* n : ordered) {
        if (n->IsTag("style")) {
            std::string text;
            for (const auto& c : n->GetChildren()) if (c->IsText()) text += c->GetText();
            parse(text, n->GetAttribute("data-vite-dev-id", "<style>"));
            continue;
        }
        if (!CTextUtils::IEquals(n->GetAttribute("rel"), "stylesheet")) continue;
        std::string href = n->GetAttribute("href");
        if (href.empty() || href.find("://") != std::string::npos) {
            if (!href.empty()) report.Drop(href, "remote stylesheet");
            continue;
        }
        while (!href.empty() && href[0] == '/') href.erase(0, 1);
        std::string text;
        const std::string path = (std::filesystem::u8path(htmlDir) / std::filesystem::u8path(href)).u8string();
        if (!ReadFile(path, text)) { report.Drop(href, "stylesheet not found at " + path); continue; }
        parse(text, href);
    }
}

std::string CHtmlConverter::Effective(const CLvmlNode& node, const std::string& property, const SContext& ctx)
{
    // Inline style wins.
    if (const std::string* style = node.FindAttribute("style")) {
        std::string value;
        for (const CLvssDeclaration& d : CLvssParser::ParseDeclarations(*style))
            if (d.property == property) value = d.value;
        if (!value.empty()) return CTextUtils::ToLower(CTextUtils::Trim(value));
    }
    uint32_t bestSpec = 0;
    size_t bestOrder = 0;
    bool found = false;
    std::string value;
    for (const CLvssRule& r : ctx.css->GetRules()) {
        const CLvssDeclaration* decl = nullptr;
        for (const CLvssDeclaration& d : r.declarations) if (d.property == property) decl = &d;
        if (!decl) continue;
        for (const CLvssSelector& s : r.selectors) {
            if (!s.GetStates().empty() || !s.GetPart().empty() || !s.Matches(node)) continue;
            const uint32_t spec = s.GetSpecificity();
            if (!found || spec > bestSpec || (spec == bestSpec && r.order >= bestOrder)) {
                found = true;
                bestSpec = spec;
                bestOrder = r.order;
                value = decl->value;
            }
        }
    }
    return CTextUtils::ToLower(CTextUtils::Trim(ctx.css->ResolveVariables(value)));
}

std::string CHtmlConverter::DisplayOf(const CLvmlNode& node, const SContext& ctx)
{
    const std::string d = Effective(node, "display", ctx);
    if (!d.empty()) return d;
    static const char* kInline[] = { "span", "a", "b", "strong", "i", "em", "small", "img", "label", "button", "input",
                                     "select", "textarea", "code", "u", "s", "sub", "sup", "mark", "svg", "br" };
    for (const char* t : kInline) if (node.IsTag(t)) return "inline";
    return "block";
}

bool CHtmlConverter::IsOutOfFlow(const CLvmlNode& node, const SContext& ctx)
{
    const std::string p = Effective(node, "position", ctx);
    return p == "absolute" || p == "fixed" || DisplayOf(node, ctx) == "none";
}

bool CHtmlConverter::IsSkipped(const CLvmlNode& node)
{
    static const char* kSkip[] = { "script", "style", "link", "meta", "noscript", "template", "head", "title", "base" };
    for (const char* t : kSkip) if (node.IsTag(t)) return true;
    if (node.IsTag("input") && CTextUtils::IEquals(node.GetAttribute("type"), "hidden")) return true;
    return false;
}

std::string CHtmlConverter::MapTag(const CLvmlNode& node, SContext& ctx)
{
    const std::string tag = CTextUtils::ToLower(node.GetTag());
    if (tag == "img") return "img";
    if (tag == "input") {
        const std::string type = CTextUtils::ToLower(node.GetAttribute("type", "text"));
        if (type == "checkbox") return "checkbox";
        if (type == "radio") { ctx.report->Note("radio inputs became checkboxes: group them in code"); return "checkbox"; }
        if (type == "range") return "slider";
        if (type == "button" || type == "submit" || type == "reset") return "button";
        return "input";
    }
    if (tag == "textarea") return "textarea";
    if (tag == "select") return "dropdown";
    if (tag == "progress" || tag == "meter") return "bar";
    if (tag == "label") return node.HasElementChildren() ? "div" : "label";
    if (tag == "svg") { ctx.report->Drop("<svg> inline", "save the icon as PNG and use <img>"); return std::string(); }
    if (tag == "video" || tag == "canvas" || tag == "iframe" || tag == "audio") {
        ctx.report->Drop("<" + tag + ">", "replaced by an empty container");
        return "div";
    }
    static const char* kKept[] = { "div", "p", "h1", "h2", "h3", "h4", "h5", "h6", "span", "a", "ul", "ol", "li", "header",
                                   "footer", "nav", "main", "aside", "article", "form", "figure", "figcaption", "strong",
                                   "b", "i", "em", "small", "fieldset", "legend", "dl", "dt", "dd", "blockquote", "pre",
                                   "code", "table", "tr", "td", "th", "thead", "tbody", "button", "section" };
    for (const char* k : kKept) if (tag == k) return tag;
    ctx.report->Note("unknown tags became <div>: <" + tag + ">");
    return "div";
}

void CHtmlConverter::CopyAttributes(const CLvmlNode& in, CLvmlNode& out, const std::string& tag, SContext& ctx)
{
    for (const CLvmlNode::Attribute& a : in.GetAttributes()) {
        const std::string name = CTextUtils::ToLower(a.first);
        if (name == "id" || name == "class" || name == "hidden" || name == "disabled" || name == "checked" ||
            name == "placeholder" || name == "href" || name == "value" || name == "min" || name == "max" ||
            name == "maxlength" || CTextUtils::StartsWith(name, "data-")) {
            if (name == "value" && tag == "checkbox") continue;
            out.SetAttribute(name, a.second);
        } else if (name == "src") {
            const std::string src = CCssConverter::RewriteAssetUrl(a.second, *ctx.report);
            if (!src.empty()) out.SetAttribute("src", src);
        } else if (name == "style") {
            const std::vector<CLvssDeclaration> decls =
                CCssConverter::ConvertDeclarations(CLvssParser::ParseDeclarations(a.second), *ctx.report);
            std::string style;
            for (const CLvssDeclaration& d : decls) style += d.property + ": " + d.value + "; ";
            if (!style.empty()) out.SetAttribute("style", std::string(CTextUtils::Trim(style)));
        } else if (name == "type" && tag == "input" && CTextUtils::IEquals(a.second, "password")) {
            out.SetAttribute("type", "password");
        }
    }
    // Convention: <… data-action="name"> becomes an lvml handler.
    if (const std::string* action = in.FindAttribute("data-action")) out.SetAttribute("onclick", *action);
    if (tag == "bar" && in.HasAttribute("value")) out.SetAttribute("value", in.GetAttribute("value"));
}

void CHtmlConverter::ApplyFlow(const CLvmlNode& in, CLvmlNode& out, const std::string& tag, SContext& ctx)
{
    if (!ctx.options->flowLayout) return;
    static const char* kLeaf[] = { "img", "checkbox", "slider", "input", "textarea", "dropdown", "bar", "label" };
    for (const char* t : kLeaf) if (tag == t) return;

    const std::string display = DisplayOf(in, ctx);
    if (display == "none") return;
    const bool isFlex = display == "flex" || display == "inline-flex";
    const bool isGrid = display == "grid" || display == "inline-grid";

    std::vector<const CLvmlNode*> flow;
    bool hasText = false;
    for (const auto& c : in.GetChildren()) {
        if (c->IsText()) { if (!CTextUtils::Trim(c->GetText()).empty()) hasText = true; continue; }
        if (IsSkipped(*c) || c->IsTag("br") || IsOutOfFlow(*c, ctx)) continue;
        flow.push_back(c.get());
    }
    if (flow.empty()) return;

    if (isGrid) { ctx.report->Drop("display: grid", "approximated as a wrapping row"); out.AddClass("lv-row"); return; }

    bool column = false;
    if (isFlex) {
        const std::string dir = Effective(in, "flex-direction", ctx);
        const std::string flowProp = Effective(in, "flex-flow", ctx);
        const std::string align = Effective(in, "align-items", ctx);
        column = CTextUtils::StartsWith(dir, "column") || CTextUtils::StartsWith(flowProp, "column");
        // CSS stretches flex items across the cross axis by default; LVGL sizes them to content.
        if (column && (align.empty() || align == "stretch" || align == "normal")) {
            for (const auto& c : out.GetChildren())
                if (c->IsElement() && !c->HasClass("lv-inline")) c->AddClass("lv-fill");
        }
        // CSS shrinks a 100% item to the space left (flex-shrink: 1); LVGL would overflow. Let it grow instead.
        for (const auto& c : out.GetChildren()) {
            const auto src = ctx.sources.find(c.get());
            if (src == ctx.sources.end() || IsOutOfFlow(*src->second, ctx)) continue;
            if (Effective(*src->second, column ? "height" : "width", ctx) == "100%") c->AddClass("lv-grow");
        }
        return;
    }

    bool allInline = true;
    for (const CLvmlNode* c : flow) {
        const std::string d = DisplayOf(*c, ctx);
        if (!(d == "inline" || d == "inline-block" || d == "inline-flex")) allInline = false;
    }
    if (allInline && hasText) return; // inline formatting context: the builder makes one label
    out.AddClass(allInline ? "lv-row" : "lv-col");
    if (allInline) return;

    // Block children fill the column like block boxes do.
    for (const auto& c : out.GetChildren()) {
        const auto src = ctx.sources.find(c.get());
        if (src == ctx.sources.end() || IsOutOfFlow(*src->second, ctx)) continue;
        const std::string d = DisplayOf(*src->second, ctx);
        if ((d == "block" || d == "flex" || d == "grid" || d == "list-item" || d == "table") &&
            Effective(*src->second, "width", ctx).empty() && !c->IsTag("img"))
            c->AddClass("lv-fill");
    }
}

void CHtmlConverter::ConvertElement(const CLvmlNode& in, CLvmlNode& parentOut, SContext& ctx)
{
    if (IsSkipped(in)) return;
    if (in.IsTag("br")) { parentOut.AppendElement("br"); return; }
    const std::string tag = MapTag(in, ctx);
    if (tag.empty()) return;

    CLvmlNode* out = parentOut.AppendElement(tag);
    ctx.sources[out] = &in;
    CopyAttributes(in, *out, tag, ctx);

    if (tag == "dropdown") {
        for (const auto& c : in.GetChildren())
            if (c->IsTag("option")) {
                CLvmlNode* opt = out->AppendElement("option");
                if (c->HasAttribute("selected")) opt->SetAttribute("selected", "");
                opt->AppendText(c->GetInnerText());
            }
        return;
    }
    if (tag == "img" || tag == "input" || tag == "slider" || tag == "bar") return;
    if (tag == "checkbox") {
        // The visible text usually lives in a sibling <label>; keep the element itself text-free.
        return;
    }
    // background-size: cover/contain cannot be expressed with an LVGL bg image (drawn unscaled):
    // put the picture into a stretched <img> behind the content instead.
    const std::string bgSize = Effective(in, "background-size", ctx);
    if (bgSize == "cover" || bgSize == "contain" || CTextUtils::StartsWith(bgSize, "100%")) {
        std::string bg = Effective(in, "background-image", ctx);
        if (bg.empty()) bg = Effective(in, "background", ctx);
        std::string url;
        const size_t at = bg.find("url(");
        if (at != std::string::npos && CLvssValue::ParseUrl(bg.substr(at, bg.find(')', at) - at + 1), url) &&
            !CTextUtils::StartsWith(url, "data:")) {
            CLvmlNode* img = out->AppendElement("img");
            img->SetAttribute("class", "lv-bg");
            img->SetAttribute("src", CCssConverter::RewriteAssetUrl(url, *ctx.report));
            img->SetAttribute("style", bgSize == "contain" ? "image-fit: contain;" : bgSize == "cover" ? "image-fit: cover;" : "image-fit: stretch;");
            out->SetAttribute("data-bg", "1");
        }
    }
    ConvertChildren(in, *out, ctx);
    ApplyFlow(in, *out, tag, ctx);
}

void CHtmlConverter::ConvertChildren(const CLvmlNode& in, CLvmlNode& out, SContext& ctx)
{
    for (const auto& c : in.GetChildren()) {
        if (c->IsText()) {
            const std::string text = CTextUtils::CollapseWhitespace(c->GetText());
            if (!CTextUtils::Trim(text).empty()) out.AppendText(text);
            continue;
        }
        ConvertElement(*c, out, ctx);
    }
}

bool CHtmlConverter::Convert(const std::string& html, const std::string& htmlDir, const SOptions& options, SResult& out)
{
    CLvmlDocument input;
    CLvmlParser::SOptions parseOptions;
    parseOptions.html = true;
    std::vector<std::string> errors;
    CLvmlParser::Parse(html, input, parseOptions, &errors);
    for (const std::string& e : errors) out.report.Note("html: " + e);

    CLvmlNode* body = input.GetRoot().FindFirst("body");
    if (!body) body = &input.GetRoot();

    CLvssStyleSheet css;
    CollectStyles(input.GetRoot(), htmlDir, css, out.report);

    SContext ctx;
    ctx.css     = &css;
    ctx.report  = &out.report;
    ctx.options = &options;

    // ---- markup ----
    CLvmlDocument doc;
    CLvmlNode* lvml = doc.GetRoot().AppendElement("lvml");
    CLvmlNode* head = lvml->AppendElement("head");
    const std::string title = options.title.empty() ? input.GetTitle() : options.title;
    if (!title.empty()) head->AppendElement("title")->AppendText(title);
    CLvmlNode* link = head->AppendElement("link");
    link->SetAttribute("rel", "stylesheet");
    link->SetAttribute("href", options.styleSheetName);

    CLvmlNode* screen = lvml->AppendElement("screen");
    CopyAttributes(*body, *screen, "screen", ctx);
    ConvertChildren(*body, *screen, ctx);
    ApplyFlow(*body, *screen, "screen", ctx);
    // `body`/`html` selectors now style <screen>.
    screen->AddClass("lv-body");
    out.lvml = "<!-- generated by html2lvml -->\n" + doc.ToString();

    // ---- styles ----
    CLvssStyleSheet generated;
    CLvssParser::Parse(kGeneratedRules, generated);
    CLvssStyleSheet converted = CCssConverter::ConvertStyleSheet(css, out.report);
    generated.Append(converted);

    std::string lvss = generated.ToString();
    // html/body/#root selectors → the screen.
    lvss = CTextUtils::Replace(lvss, "\nhtml {", "\n.lv-body {");
    lvss = CTextUtils::Replace(lvss, "\nbody {", "\n.lv-body {");
    lvss = CTextUtils::Replace(lvss, "\n:root {", "\n.lv-body {"); // :root in lvml is <lvml>, not the screen
    if (CTextUtils::StartsWith(lvss, ":root {")) lvss = ".lv-body {" + lvss.substr(7);
    out.lvss = lvss;
    return true;
}
